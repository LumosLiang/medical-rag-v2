-- SPCS 一次性引导，不属于 deploy.sql。包含账户权限变更，执行前须确认。
USE ROLE ACCOUNTADMIN;

CREATE COMPUTE POOL IF NOT EXISTS MEDRAG_APP_POOL
  MIN_NODES = 1
  MAX_NODES = 1
  INSTANCE_FAMILY = CPU_X64_XS
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE
  AUTO_SUSPEND_SECS = 300;

GRANT OWNERSHIP ON COMPUTE POOL MEDRAG_APP_POOL TO ROLE MEDRAG_ADMIN COPY CURRENT GRANTS;
GRANT BIND SERVICE ENDPOINT ON ACCOUNT TO ROLE MEDRAG_ADMIN;

USE ROLE MEDRAG_ADMIN;
USE DATABASE MEDRAG;
CREATE IMAGE REPOSITORY IF NOT EXISTS OPS.APP_IMAGES;
CREATE STAGE IF NOT EXISTS OPS.APP_SPECS;
SHOW IMAGE REPOSITORIES LIKE 'APP_IMAGES' IN SCHEMA OPS;
