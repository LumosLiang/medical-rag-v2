-- 应用实现、镜像推送和 setup 完成后单独执行；不混进入库部署。
USE ROLE MEDRAG_ADMIN;
USE DATABASE MEDRAG;

PUT file://deploy/spcs/service.yaml @OPS.APP_SPECS AUTO_COMPRESS = FALSE OVERWRITE = TRUE;

CREATE SERVICE IF NOT EXISTS OPS.MEDICAL_RAG_APP
  IN COMPUTE POOL MEDRAG_APP_POOL
  FROM @OPS.APP_SPECS
  SPECIFICATION_FILE = 'service.yaml'
  MIN_INSTANCES = 1
  MAX_INSTANCES = 1;

-- 首次建服务后授权前端访问；后续升级同一服务用下方 ALTER，不 DROP。
GRANT SERVICE ROLE OPS.MEDICAL_RAG_APP!UI_ACCESS TO ROLE MEDRAG_ADMIN;
ALTER SERVICE OPS.MEDICAL_RAG_APP
  FROM @OPS.APP_SPECS
  SPECIFICATION_FILE = 'service.yaml';

SHOW SERVICE CONTAINERS IN SERVICE OPS.MEDICAL_RAG_APP;
SHOW ENDPOINTS IN SERVICE OPS.MEDICAL_RAG_APP;
